export const FONT_CHARS = ' 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.,!\'*-x:';

export function paintFontTexture(scene) {
  const cellW = 6;
  const cellH = 8;
  const cols = 13;
  const rows = Math.ceil(FONT_CHARS.length / cols);
  const canvasTex = scene.textures.createCanvas('pixfont', cols * cellW, rows * cellH);
  const ctx = canvasTex.getContext();
  ctx.clearRect(0, 0, cols * cellW, rows * cellH);
  ctx.fillStyle = '#ffffff';
  for (let i = 0; i < FONT_CHARS.length; i += 1) {
    const glyph = GLYPHS[FONT_CHARS[i]];
    const ox = (i % cols) * cellW;
    const oy = Math.floor(i / cols) * cellH;
    if (!glyph) continue;
    for (let y = 0; y < glyph.length; y += 1) {
      for (let x = 0; x < glyph[y].length; x += 1) {
        if (glyph[y][x] === '1') ctx.fillRect(ox + x, oy + y, 1, 1);
      }
    }
  }
  canvasTex.refresh();
  scene.cache.bitmapFont.add(
    'pix',
    Phaser.GameObjects.RetroFont.Parse(scene, {
      image: 'pixfont',
      width: cellW,
      height: cellH,
      chars: FONT_CHARS,
      charsPerRow: cols,
      spacing: { x: 0, y: 0 },
    }),
  );
}

export function label(scene, x, y, text, size = 1) {
  const node = scene.add.bitmapText(x, y, 'pix', text);
  node.setScale(size);
  return node;
}
